"""Run every eval and write evals/report.md. One command, one artifact.

    python -m credit_evals.run_evals
"""
import json
import sys
from pathlib import Path

from . import evals as E
from .data import TARGET, load
from .ml_model import make_split, predict_pd, train

REPORT = Path(__file__).resolve().parents[2] / "evals" / "report.md"


def _table(rows: list[dict]) -> str:
    if not rows:
        return "_(none)_\n"
    cols = list(rows[0])
    out = ["| " + " | ".join(cols) + " |",
           "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"


def main() -> int:
    df = load()
    split = make_split(df)
    model = train(split)
    scores = predict_pd(model, split.X_test)
    y = split.y_test
    df_test = df.iloc[split.test_index]

    disc = E.eval_discrimination(y, scores)
    cal = E.eval_calibration(y, scores)
    cost = E.eval_cost(y, scores)
    thr = cost["best"]["threshold"]

    llm = E.run_llm_path(df_test)
    agree = E.eval_agreement(scores, llm, df_test)
    slices = E.eval_slices(df_test, y, scores, thr)
    ground = E.eval_groundedness(llm)
    abst = E.eval_abstention(llm, y)

    src = ground["source"]
    live_note = ("**LLM path source: deterministic stub (no API key set). "
                 "The live Claude path is UNTESTED-LIVE.**" if src == "stub"
                 else "LLM path source: live API.")

    md = [
        "# Eval report — credit-risk-evals",
        f"_Generated by `python -m credit_evals.run_evals` · test set n={disc['n']} "
        f"(30% holdout, stratified, seed fixed) · base default rate {disc['base_default_rate']}_",
        "", live_note, "",
        "## 1 · Discrimination (ML path)",
        f"AUC **{disc['auc']}** · KS **{disc['ks']}**", "",
        "## 2 · Calibration (ML path)",
        f"Brier **{cal['brier']}** · ECE **{cal['ece']}**", "",
        _table(cal["reliability"]),
        "## 3 · Cost, on the dataset's own 5:1 matrix",
        f"Best threshold **{thr}** → total cost **{cost['best']['total_cost']}** "
        f"({cost['best']['defaulters_approved']} defaulters approved, "
        f"{cost['best']['good_declined']} good applicants declined). "
        f"Approve-all / decline-all costs {cost['cost_approve_or_decline_all']}.", "",
        _table(cost["sweep"][1:14:2]),
        "## 4 · ML vs LLM ranking agreement",
        f"Spearman ρ **{agree['spearman_rho']}** · Kendall τ **{agree['kendall_tau']}** "
        f"on {agree['n_graded']} graded applications.",
        f"Where ML says safe (bottom 30% PD) but LLM says E: "
        f"{agree['ml_safe_llm_risky']['n']} cases, actual default rate "
        f"{agree['ml_safe_llm_risky']['actual_default_rate']}. "
        f"Where ML says risky (top 30%) but LLM says A: "
        f"{agree['ml_risky_llm_safe']['n']} cases, actual default rate "
        f"{agree['ml_risky_llm_safe']['actual_default_rate']}.", "",
        "## 5 · Slices the model never saw as features",
    ]
    for col, rows in slices.items():
        md += [f"### {col}", "", _table(rows)]
    md += [
        "## 6 · Groundedness gate (LLM path)",
        f"Fired on **{ground['gate_fired']}/{ground['n']}** rationales "
        f"(rate {ground['gate_fire_rate']}). A fired gate means the rationale "
        "cited a figure not present in the application and was withheld.", "",
        "## 7 · Abstention (LLM path)",
        f"Abstained on {abst['abstained']}/{ground['n']} "
        f"(rate {abst['abstention_rate']}).", "",
    ]
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(md))
    print(f"wrote {REPORT}")
    print(json.dumps({"auc": disc["auc"], "ks": disc["ks"],
                      "brier": cal["brier"], "ece": cal["ece"],
                      "best_threshold": thr,
                      "best_cost": cost["best"]["total_cost"],
                      "spearman": agree["spearman_rho"],
                      "gate_fire_rate": ground["gate_fire_rate"],
                      "llm_source": src}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
